document.addEventListener('DOMContentLoaded', () => {
  renderNotices('all');
  initNoticeFilters();
  initNoticeSearch();
});

function renderNotices(category = 'all', searchQuery = '') {
  const container = document.getElementById('noticesContainer');
  if (!container) return;

  let filtered = noticesData;

  if (category !== 'all') {
    filtered = filtered.filter(n => n.category === category);
  }

  if (searchQuery.trim() !== '') {
    const q = searchQuery.toLowerCase();
    filtered = filtered.filter(n => 
      n.title_ne.toLowerCase().includes(q) || 
      n.title_en.toLowerCase().includes(q) ||
      n.content_ne.toLowerCase().includes(q)
    );
  }

  if (filtered.length === 0) {
    container.innerHTML = `
      <div style="text-align: center; padding: 3rem; color: var(--text-muted);">
        <i class="fa-regular fa-folder-open" style="font-size: 2.5rem; margin-bottom: 0.8rem; display: block;"></i>
        <p>कुनै सूचना भेटिएन / No notices found matching your criteria.</p>
      </div>
    `;
    return;
  }

  const isEn = (typeof currentLang !== 'undefined' && currentLang === 'en');

  container.innerHTML = filtered.map(notice => {
    const title = isEn ? notice.title_en : notice.title_ne;
    const catLabel = isEn ? notice.categoryLabel_en : notice.categoryLabel_ne;
    const month = isEn ? notice.month_en : notice.month_ne;
    const dateStr = isEn ? `${notice.date_ad} (BS: ${notice.date_bs})` : `${notice.date_bs} (${notice.date_ad})`;
    const btnText = isEn ? '<i class="fa-solid fa-eye"></i> View Details' : '<i class="fa-solid fa-eye"></i> हेर्नुहोस्';

    return `
      <div class="notice-item-card" data-category="${notice.category}">
        <div class="notice-date-badge">
          <div class="notice-bs-day">${notice.day}</div>
          <div class="notice-bs-month">${month}</div>
        </div>
        <div class="notice-title-box">
          <span class="notice-cat-tag ${notice.catClass}">
            ${catLabel} ${notice.isNew ? '<span class="badge-pill" style="background:#EF4444;color:#fff;margin-left:4px;">NEW</span>' : ''}
          </span>
          <h4 class="notice-heading">
            <a href="javascript:void(0)" onclick="viewNoticeDetail('${notice.id}')">${title}</a>
          </h4>
          <p style="font-size: 0.84rem; color: var(--text-muted); margin-top: 0.2rem;">
            <i class="fa-regular fa-clock"></i> ${dateStr} | <i class="fa-regular fa-file-pdf"></i> ${notice.file_name}
          </p>
        </div>
        <div>
          <button class="btn btn-outline-primary btn-sm" onclick="viewNoticeDetail('${notice.id}')">
            ${btnText}
          </button>
        </div>
      </div>
    `;
  }).join('');
}

function initNoticeFilters() {
  const buttons = document.querySelectorAll('.notices-filter-nav .filter-pill-btn');
  buttons.forEach(btn => {
    btn.addEventListener('click', () => {
      buttons.forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      const cat = btn.getAttribute('data-filter') || 'all';
      const searchInput = document.getElementById('noticeSearchInput');
      renderNotices(cat, searchInput ? searchInput.value : '');
    });
  });
}

function initNoticeSearch() {
  const searchInput = document.getElementById('noticeSearchInput');
  if (!searchInput) return;

  searchInput.addEventListener('input', (e) => {
    const activeBtn = document.querySelector('.notices-filter-nav .filter-pill-btn.active');
    const cat = activeBtn ? activeBtn.getAttribute('data-filter') : 'all';
    renderNotices(cat, e.target.value);
  });
}

window.viewNoticeDetail = function(id) {
  const notice = noticesData.find(n => n.id === id);
  if (!notice) return;

  const modal = document.getElementById('noticeDetailModal');
  const titleEl = document.getElementById('noticeDetailTitle');
  const metaEl = document.getElementById('noticeDetailMeta');
  const bodyEl = document.getElementById('noticeDetailBody');
  const dlBtn = document.getElementById('noticeDownloadBtn');

  if (!modal) return;

  if (titleEl) titleEl.textContent = notice.title_ne;
  if (metaEl) {
    metaEl.innerHTML = `
      <span class="notice-cat-tag ${notice.catClass}">${notice.categoryLabel_ne}</span>
      <span><i class="fa-regular fa-calendar-check"></i> ${notice.date_bs} (${notice.date_ad})</span>
      <span><i class="fa-solid fa-hashtag"></i> सूचना नं: ${notice.id}</span>
    `;
  }
  if (bodyEl) {
    bodyEl.innerHTML = `
      <div style="background: var(--bg-alt); border-left: 4px solid var(--primary); padding: 1.25rem; border-radius: 6px; line-height: 1.8; font-size: 0.98rem; white-space: pre-line; color: var(--text-main);">
        ${notice.content_ne}
      </div>
      <div style="margin-top: 1.5rem; padding: 1rem; background: var(--primary-subtle); border-radius: 8px; display: flex; align-items: center; justify-content: space-between;">
        <div>
          <strong><i class="fa-solid fa-file-pdf" style="color: #EF4444; font-size: 1.4rem; margin-right: 0.5rem;"></i> ${notice.file_name}</strong>
          <div style="font-size: 0.8rem; color: var(--text-muted);">PDF Document • CTEVT Official Seal Verified</div>
        </div>
        <button class="btn btn-primary btn-sm" onclick="simulateNoticeDownload('${notice.file_name}')">
          <i class="fa-solid fa-download"></i> PDF Download
        </button>
      </div>
    `;
  }

  modal.classList.add('is-open');
};

window.simulateNoticeDownload = function(filename) {
  const toast = document.createElement('div');
  toast.style.position = 'fixed';
  toast.style.bottom = '2rem';
  toast.style.left = '50%';
  toast.style.transform = 'translateX(-50%)';
  toast.style.background = '#059669';
  toast.style.color = '#fff';
  toast.style.padding = '0.75rem 1.5rem';
  toast.style.borderRadius = '30px';
  toast.style.boxShadow = '0 10px 25px rgba(0,0,0,0.2)';
  toast.style.zIndex = '3000';
  toast.style.fontWeight = '600';
  toast.innerHTML = `<i class="fa-solid fa-circle-check"></i> डाउनलोड सुरु भयो: ${filename}`;
  document.body.appendChild(toast);

  setTimeout(() => {
    toast.style.opacity = '0';
    toast.style.transition = 'opacity 0.4s ease';
    setTimeout(() => toast.remove(), 400);
  }, 2500);
};
