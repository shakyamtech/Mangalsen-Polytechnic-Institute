// Dynamic Breaking Ticker Sync from Admin
function initDynamicTicker() {
  try {
    const raw = localStorage.getItem('mpi_tickers');
    if (raw) {
      const tickers = JSON.parse(raw);
      if (Array.isArray(tickers) && tickers.length > 0) {
        const container = document.querySelector('.ticker-items');
        if (container) {
          container.innerHTML = tickers.map(t => `
            <span class="ticker-item">
              <span class="badge-pill">${t.tag || 'NEW'}</span>
              <a href="javascript:void(0)" onclick="viewNoticeDetail('N-2083-104')">${t.text}</a>
            </span>
          `).join('');
        }
      }
    }
  } catch (e) {
    console.warn('Dynamic ticker render error', e);
  }
}

// Live Bikram Sambat Date Clock
function initLiveBikramSambatDate() {
  const dateElement = document.getElementById('liveNepaliDate');
  if (!dateElement) return;

  const now = new Date();
  const options = { weekday: 'long', year: 'numeric', month: 'short', day: 'numeric' };
  const enDate = now.toLocaleDateString('en-US', options);
  
  const bsString = (currentLang === 'ne') ? "२०८३ आश्विन १४, बुधबार" : "Wednesday, 14 Ashwin 2083";
  dateElement.innerHTML = `<i class="fa-regular fa-calendar-days"></i> ${bsString} (${enDate})`;
}

// Hero Slider
function initHeroSlider() {
  const slides = document.querySelectorAll('.hero-slide');
  const dots = document.querySelectorAll('.slider-dot');
  const prevBtn = document.getElementById('heroPrevBtn');
  const nextBtn = document.getElementById('heroNextBtn');
  
  if (slides.length === 0) return;
  
  let currentSlide = 0;
  let slideInterval = null;

  function showSlide(index) {
    slides.forEach(s => s.classList.remove('active'));
    dots.forEach(d => d.classList.remove('active'));

    currentSlide = (index + slides.length) % slides.length;
    slides[currentSlide].classList.add('active');
    if (dots[currentSlide]) dots[currentSlide].classList.add('active');
  }

  function startAutoSlide() {
    slideInterval = setInterval(() => {
      showSlide(currentSlide + 1);
    }, 6000);
  }

  function stopAutoSlide() {
    if (slideInterval) clearInterval(slideInterval);
  }

  if (prevBtn) {
    prevBtn.addEventListener('click', () => {
      stopAutoSlide();
      showSlide(currentSlide - 1);
      startAutoSlide();
    });
  }

  if (nextBtn) {
    nextBtn.addEventListener('click', () => {
      stopAutoSlide();
      showSlide(currentSlide + 1);
      startAutoSlide();
    });
  }

  dots.forEach((dot, idx) => {
    dot.addEventListener('click', () => {
      stopAutoSlide();
      showSlide(idx);
      startAutoSlide();
    });
  });

  startAutoSlide();
}

// Language Switcher
function initLanguage() {
  const toggleBtn = document.getElementById('langToggleBtn');
  const savedLang = localStorage.getItem('mpi_lang') || 'ne';
  setLanguage(savedLang);

  if (toggleBtn) {
    toggleBtn.addEventListener('click', () => {
      const nextLang = (currentLang === 'ne') ? 'en' : 'ne';
      setLanguage(nextLang);
    });
  }
}

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('mpi_lang', lang);
  document.documentElement.setAttribute('lang', lang);
  
  const toggleBtn = document.getElementById('langToggleBtn');
  if (toggleBtn) {
    toggleBtn.innerHTML = (lang === 'ne') 
      ? `<i class="fa-solid fa-globe"></i> English` 
      : `<i class="fa-solid fa-globe"></i> नेपाली`;
  }

  const trans = translations[lang] || translations.ne;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (trans[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.setAttribute('placeholder', trans[key]);
      } else {
        el.textContent = trans[key];
      }
    }
  });

  initLiveBikramSambatDate();

  // Re-render notices in current language if notice module loaded
  if (typeof renderNotices === 'function') {
    const activeBtn = document.querySelector('.notices-filter-nav .filter-pill-btn.active');
    const cat = activeBtn ? activeBtn.getAttribute('data-filter') : 'all';
    renderNotices(cat);
  }

  // Update calculator result if calculator exists
  if (typeof checkEligibility === 'function') {
    checkEligibility();
  }
}

// Dark / Light Theme
function initTheme() {
  const themeBtn = document.getElementById('themeToggleBtn');
  const savedTheme = localStorage.getItem('mpi_theme') || 'light';
  
  document.documentElement.setAttribute('data-theme', savedTheme);
  updateThemeIcon(savedTheme);

  if (themeBtn) {
    themeBtn.addEventListener('click', () => {
      const cur = document.documentElement.getAttribute('data-theme');
      const nextTheme = cur === 'dark' ? 'light' : 'dark';
      document.documentElement.setAttribute('data-theme', nextTheme);
      localStorage.setItem('mpi_theme', nextTheme);
      updateThemeIcon(nextTheme);
    });
  }
}

function updateThemeIcon(theme) {
  const themeBtn = document.getElementById('themeToggleBtn');
  if (!themeBtn) return;
  themeBtn.innerHTML = (theme === 'dark') 
    ? `<i class="fa-solid fa-sun"></i> Light` 
    : `<i class="fa-solid fa-moon"></i> Dark`;
}

// Accessibility font size
function initAccessibility() {
  const btnSm = document.getElementById('fontSm');
  const btnMd = document.getElementById('fontMd');
  const btnLg = document.getElementById('fontLg');

  function setFontSizeClass(cls) {
    document.documentElement.classList.remove('font-sm', 'font-md', 'font-lg');
    document.documentElement.classList.add(cls);
    [btnSm, btnMd, btnLg].forEach(b => b?.classList.remove('active'));
    if (cls === 'font-sm') btnSm?.classList.add('active');
    if (cls === 'font-md') btnMd?.classList.add('active');
    if (cls === 'font-lg') btnLg?.classList.add('active');
  }

  btnSm?.addEventListener('click', () => setFontSizeClass('font-sm'));
  btnMd?.addEventListener('click', () => setFontSizeClass('font-md'));
  btnLg?.addEventListener('click', () => setFontSizeClass('font-lg'));
}

// Notice Modal Popup on Entry
function initNoticeModalPopup() {
  const popup = document.getElementById('urgentNoticeModal');
  const closeBtn = document.getElementById('closeUrgentNotice');
  const dismissCheckbox = document.getElementById('dontShowAgainNotice');

  if (!popup) return;

  // Check admin customized popup settings
  try {
    const rawConfig = localStorage.getItem('mpi_popup_settings');
    if (rawConfig) {
      const config = JSON.parse(rawConfig);
      if (config.enabled === false) {
        return; // Disabled by admin
      }
      if (config.badge) {
        const badgeEl = document.getElementById('urgentNoticeBadge');
        if (badgeEl) badgeEl.textContent = config.badge;
      }
      if (config.title) {
        const titleEl = document.getElementById('urgentNoticeHeading');
        if (titleEl) titleEl.textContent = config.title;
      }
      if (config.desc) {
        const descEl = document.getElementById('urgentNoticeDesc');
        if (descEl) descEl.textContent = config.desc;
      }
      if (config.headerTitle) {
        const headerEl = document.getElementById('urgentModalTitleText');
        if (headerEl) headerEl.textContent = config.headerTitle;
      }
    }
  } catch (e) {
    console.warn('Popup settings parse error', e);
  }

  const hasDismissed = localStorage.getItem('mpi_notice_dismissed_v1');
  if (!hasDismissed) {
    setTimeout(() => {
      popup.classList.add('is-open');
    }, 1200);
  }

  closeBtn?.addEventListener('click', () => {
    popup.classList.remove('is-open');
    if (dismissCheckbox && dismissCheckbox.checked) {
      localStorage.setItem('mpi_notice_dismissed_v1', 'true');
    }
  });

  popup.addEventListener('click', (e) => {
    if (e.target === popup) {
      popup.classList.remove('is-open');
    }
  });
}

// Mobile Nav Toggle
function initMobileNav() {
  const toggleBtn = document.getElementById('mobileNavToggle');
  const navList = document.getElementById('mainNavList');

  toggleBtn?.addEventListener('click', () => {
    navList?.classList.toggle('is-open');
  });

  document.querySelectorAll('.nav-link').forEach(link => {
    link.addEventListener('click', () => {
      if (window.innerWidth <= 992) {
        navList?.classList.remove('is-open');
      }
    });
  });
}

// Floating Action Back to Top & Scroll
function initScrollEffects() {
  const fabTop = document.getElementById('fabBackToTop');

  window.addEventListener('scroll', () => {
    if (window.scrollY > 400) {
      fabTop?.classList.add('is-visible');
    } else {
      fabTop?.classList.remove('is-visible');
    }
  });

  fabTop?.addEventListener('click', () => {
    window.scrollTo({ top: 0, behavior: 'smooth' });
  });
}

